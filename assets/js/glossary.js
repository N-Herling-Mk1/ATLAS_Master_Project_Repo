/* research-deck -- glossary page.
   Data: window.DECK_GLOSSARY {revised, terms[]} and DECK_PROJECTS / DECK_META, all from assets/js/registry.js
   (generated by tools/build_deck.py from glossary/glossary.json). Deep link: glossary.html#<term-key>. */
(() => {
  "use strict";
  const GL = window.DECK_GLOSSARY || { terms: [] };
  const T = GL.terms || [];
  const P = window.DECK_PROJECTS || [];
  const META = window.DECK_META || {};
  const PK = new Map(P.map((p) => [p.id, p]));
  const TK = new Map(T.map((t) => [t.key, t]));
  const $ = (id) => document.getElementById(id);
  const reduced = matchMedia("(prefers-reduced-motion: reduce)").matches;
  const el = (tag, cls, text) => { const e = document.createElement(tag); if (cls) e.className = cls; if (text != null) e.textContent = text; return e; };
  const MONTHS = ["JAN", "FEB", "MAR", "APR", "MAY", "JUN", "JUL", "AUG", "SEP", "OCT", "NOV", "DEC"];
  const fmtDate = (d) => { const [y, m, day] = (d || "").split("-"); return [day, m && MONTHS[+m - 1], y].filter(Boolean).join(" "); };
  const TERM_RE = /\[\[([a-z0-9-]+)(?:\|([^\]]+))?\]\]/g;
  // inline label for a [[key]] link: the term's 'inline' field, else its name with a sentence-case first letter lowered
  const inlineName = (t) => t.inline || (/^[A-Z][a-z]/.test(t.term) && !/[A-Z]/.test(t.term.slice(1)) ? t.term[0].toLowerCase() + t.term.slice(1) : t.term);

  if (META.revised) { $("site-revised").textContent = fmtDate(META.revised); $("site-revised-wrap").hidden = false; }
  $("g-count").textContent = `${T.length} TERMS`;
  $("g-revised").textContent = GL.revised ? `REVISED ${fmtDate(GL.revised)}` : "";
  if (!T.length) { $("g-list").textContent = "No glossary terms yet. Add them to glossary/glossary.json and run tools/build_deck.py."; return; }

  // text with [[key]] links -> in-page anchors
  function rich(text) {
    const out = [];
    let last = 0;
    for (const m of text.matchAll(TERM_RE)) {
      if (m.index > last) out.push(document.createTextNode(text.slice(last, m.index)));
      const t = TK.get(m[1]);
      const a = el("a", "g-xref", m[2] || (t ? inlineName(t) : m[1]));
      a.href = `#${m[1]}`;
      out.push(a);
      last = m.index + m[0].length;
    }
    if (last < text.length) out.push(document.createTextNode(text.slice(last)));
    return out;
  }

  // ---- entries, grouped by category (in the order categories first appear in glossary.json) ----
  const cats = (GL.categories || []).filter((c) => T.some((t) => t.category === c));
  T.forEach((t) => { if (!cats.includes(t.category)) cats.push(t.category); });
  const entries = [];

  $("g-list").replaceChildren(...cats.map((cat, ci) => {
    const sec = el("section", "g-cat");
    sec.id = `cat-${ci}`;
    const h = el("h3", "q-head");
    h.append(el("span", null, cat.toUpperCase()), el("span", "rule"), el("span", "count", String(T.filter((t) => t.category === cat).length)));
    sec.append(h);
    T.filter((t) => t.category === cat).forEach((t) => {
      const art = el("article", "g-entry");
      art.id = t.key;
      const head = el("div", "g-head");
      const name = el("h4", "g-term", t.term);
      const link = el("a", "g-anchor", "#");
      link.href = `#${t.key}`;
      link.title = "Link to this entry";
      head.append(name, link);
      art.append(head);
      if (t.aka && t.aka.length) art.append(el("p", "g-aka", `also: ${t.aka.join(" · ")}`));
      const sh = el("p", "g-short");
      sh.append(...rich(t.short));
      art.append(sh);
      (t.long || []).forEach((para) => {
        const pp = el("p", "g-long");
        pp.append(...rich(para));
        art.append(pp);
      });
      const foot = el("div", "g-foot");
      if (t.see && t.see.length) {
        const row = el("p", "g-row");
        row.append(el("span", "g-k", "SEE ALSO"));
        t.see.forEach((k) => {
          const s = TK.get(k);
          const a = el("a", "g-chip", s ? s.term : k);
          a.href = `#${k}`;
          row.append(a);
        });
        foot.append(row);
      }
      if (t.used_in && t.used_in.length) {
        const row = el("p", "g-row");
        row.append(el("span", "g-k", "USED IN"));
        t.used_in.forEach((pid) => {
          const p = PK.get(pid);
          if (!p) return;
          const a = el("a", "g-chip g-proj", p.name);
          a.href = `index.html#${pid}`;
          a.style.setProperty("--pc", p.accent);
          row.append(a);
        });
        foot.append(row);
      }
      if (t.refs && t.refs.length) {
        const row = el("div", "g-row g-refs");
        row.append(el("span", "g-k", "SOURCES"));
        const ul = el("ul");
        t.refs.forEach((r) => {
          const li = el("li");
          const a = el("a", null, r.title);
          a.href = r.url; a.target = "_blank"; a.rel = "noopener";
          li.append(a);
          if (r.venue) li.append(document.createTextNode(` · ${r.venue}`));
          ul.append(li);
        });
        row.append(ul);
        foot.append(row);
      }
      if (foot.childNodes.length) art.append(foot);
      sec.append(art);
      entries.push({ t, art, hay: [t.term, ...(t.aka || []), t.short, ...(t.long || []), t.category].join(" ").toLowerCase() });
    });
    return sec;
  }));

  // ---- side index ----
  const idxItems = [];
  $("g-index").replaceChildren(...cats.map((cat, ci) => {
    const li = el("li");
    const b = el("a", "gi-cat", cat.toUpperCase());
    b.href = `#cat-${ci}`;
    li.append(b);
    const ol = el("ol");
    T.filter((t) => t.category === cat).forEach((t) => {
      const sl = el("li");
      const a = el("a", "gi-term", t.term);
      a.href = `#${t.key}`;
      sl.append(a);
      ol.append(sl);
      idxItems.push({ key: t.key, li: sl });
    });
    li.append(ol);
    return li;
  }));

  // ---- filter ----
  $("g-q").addEventListener("input", (e) => {
    const q = e.target.value.trim().toLowerCase().replace(/[\\$]/g, "");
    let shown = 0;
    entries.forEach(({ t, art, hay }) => {
      const on = !q || hay.replace(/[\\$]/g, "").includes(q);
      art.hidden = !on;
      if (on) shown++;
      const ix = idxItems.find((x) => x.key === t.key);
      if (ix) ix.li.hidden = !on;
    });
    document.querySelectorAll(".g-cat").forEach((sec) => { sec.hidden = !sec.querySelector(".g-entry:not([hidden])"); });
    $("g-empty").hidden = shown > 0;
  });

  // ---- math ----
  if (window.renderMathInElement) {
    window.renderMathInElement(document.body, {
      delimiters: [{ left: "$$", right: "$$", display: true }, { left: "$", right: "$", display: false }],
      throwOnError: false,
      ignoredTags: ["script", "noscript", "style", "textarea", "pre", "code", "option", "input"],
    });
  }

  // ---- deep links: flash the target entry ----
  function flash() {
    const k = decodeURIComponent(location.hash.slice(1));
    const t = k && $(k);
    if (!t || !t.classList.contains("g-entry")) return;
    t.scrollIntoView({ behavior: reduced ? "auto" : "smooth", block: "start" });
    t.classList.remove("flash"); void t.offsetWidth; t.classList.add("flash");
  }
  addEventListener("hashchange", flash);
  if (location.hash) {
    requestAnimationFrame(flash);
    if (document.fonts && document.fonts.ready) document.fonts.ready.then(() => { const k = location.hash.slice(1); if ($(k)) $(k).scrollIntoView({ block: "start" }); });
  }

  // ---- back to top ----
  const toTop = $("to-top");
  const syncTop = () => toTop.classList.toggle("show", scrollY > innerHeight * 0.6);
  addEventListener("scroll", syncTop, { passive: true });
  toTop.addEventListener("click", () => scrollTo({ top: 0, behavior: reduced ? "auto" : "smooth" }));
  syncTop();
})();
