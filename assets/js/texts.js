/* research-deck -- texts page (reference reviews, papers, books).
   Data: window.DECK_TEXTS {revised, categories[], texts[]} plus DECK_PROJECTS / DECK_META, all from assets/js/registry.js
   (generated by tools/build_deck.py from texts/texts.json).
   Deep links: texts.html#<key> (one entry), texts.html#project=<id>, texts.html#category=<key>. */
(() => {
  "use strict";
  const TX = window.DECK_TEXTS || { texts: [], categories: [] };
  const ITEMS = TX.texts || [];
  const CATS = TX.categories || [];
  const P = window.DECK_PROJECTS || [];
  const META = window.DECK_META || {};
  const PK = new Map(P.map((p) => [p.id, p]));
  const CK = new Map(CATS.map((c) => [c.key, c]));
  const IK = new Map(ITEMS.map((t) => [t.key, t]));
  const $ = (id) => document.getElementById(id);
  const reduced = matchMedia("(prefers-reduced-motion: reduce)").matches;
  const el = (tag, cls, text) => { const e = document.createElement(tag); if (cls) e.className = cls; if (text != null) e.textContent = text; return e; };
  const MONTHS = ["JAN", "FEB", "MAR", "APR", "MAY", "JUN", "JUL", "AUG", "SEP", "OCT", "NOV", "DEC"];
  const fmtDate = (d) => { const [y, m, day] = (d || "").split("-"); return [day, m && MONTHS[+m - 1], y].filter(Boolean).join(" "); };

  if (META.revised) { $("site-revised").textContent = fmtDate(META.revised); $("site-revised-wrap").hidden = false; }
  $("x-count").textContent = `${ITEMS.length} ${ITEMS.length === 1 ? "TEXT" : "TEXTS"}`;
  $("x-revised").textContent = TX.revised ? `REVISED ${fmtDate(TX.revised)}` : "";
  if (!ITEMS.length) { $("x-list").textContent = "No texts yet. Add them to texts/texts.json and run tools/build_deck.py."; return; }

  const F = { cat: new Set(), project: new Set(), q: "" };

  function chip(label, color, count, on, onClick, title) {
    const b = el("button", "t-chip");
    b.type = "button";
    b.style.setProperty("--cc", color);
    b.append(el("span", "t-chip-l", label));
    if (count) b.append(el("span", "t-chip-n", String(count)));
    b.setAttribute("aria-pressed", on ? "true" : "false");
    if (title) b.title = title;
    b.addEventListener("click", onClick);
    return b;
  }
  const usedCats = CATS.filter((c) => ITEMS.some((t) => t.category === c.key));
  const usedProjects = [...new Set(ITEMS.flatMap((t) => t.projects || []))]
    .filter((pid) => PK.has(pid)).sort((a, b) => (PK.get(a).order ?? 999) - (PK.get(b).order ?? 999));

  function toggle(set, key) { set.has(key) ? set.delete(key) : set.add(key); syncHash(); render(); }

  function renderFacets() {
    $("x-cats").replaceChildren(...usedCats.map((c) =>
      chip(c.label.toUpperCase(), c.color, ITEMS.filter((t) => t.category === c.key).length, F.cat.has(c.key), () => toggle(F.cat, c.key))));
    $("x-projects").replaceChildren(...usedProjects.map((pid) => {
      const p = PK.get(pid);
      return chip(p.name, p.accent, ITEMS.filter((t) => (t.projects || []).includes(pid)).length,
        F.project.has(pid), () => toggle(F.project, pid), "Texts tagged with this project");
    }));
    $("x-clear").hidden = !(F.cat.size || F.project.size || F.q);
  }

  function card(t) {
    const c = CK.get(t.category) || { color: "#c9c9c9" };
    const art = el("article", "t-item x-item");
    art.id = t.key;
    art.style.setProperty("--sc", c.color);
    const head = el("div", "t-head");
    const id = el("a", "t-id", "#");
    id.href = `#${t.key}`;
    id.title = "Link to this entry";
    head.append(id);
    if (t.format) head.append(el("span", "t-st", t.format.toUpperCase()));
    if (t.added) head.append(el("span", "t-dates", `ADDED ${fmtDate(t.added)}`));
    const title = el("a", "x-title");
    title.href = t.url;
    title.target = "_blank";
    title.rel = "noopener";
    title.title = "Open the source (new tab)";
    title.append(el("span", null, t.title), el("span", "x-arrow", "↗"));
    const meta = [t.authors, t.source, t.revision].filter(Boolean).join(" · ");
    art.append(head, title);
    if (meta) art.append(el("p", "x-meta", meta));
    if (t.note) art.append(el("p", "t-detail", t.note));
    const foot = el("div", "t-foot");
    const row = (k, nodes) => { if (!nodes.length) return; const r = el("p", "g-row"); r.append(el("span", "g-k", k), ...nodes); foot.append(r); };
    row("PROJECTS", (t.projects || []).filter((pid) => PK.has(pid)).map((pid) => {
      const p = PK.get(pid);
      const a = el("a", "g-chip g-proj", p.name);
      a.href = `index.html#${pid}`;
      a.style.setProperty("--pc", p.accent);
      return a;
    }));
    const host = (() => { try { return new URL(t.url).host; } catch { return ""; } })();
    if (host) row("SOURCE", [el("span", "g-chip x-host", host)]);
    if (foot.childNodes.length) art.append(foot);
    return art;
  }

  const hay = (t) => [t.key, t.title, t.authors || "", t.source || "", t.revision || "", t.note || "", t.format || "",
    CK.get(t.category)?.label || "", ...(t.projects || []).map((pid) => PK.get(pid)?.name || pid)].join(" ").toLowerCase();
  const match = (t) =>
    (!F.cat.size || F.cat.has(t.category)) &&
    (!F.project.size || (t.projects || []).some((pid) => F.project.has(pid))) &&
    (!F.q || hay(t).includes(F.q));

  function render() {
    renderFacets();
    const shown = ITEMS.filter(match);
    $("x-empty").hidden = shown.length > 0;
    const order = [...CATS.map((c) => c.key), ...new Set(ITEMS.map((t) => t.category).filter((k) => !CK.has(k)))];
    $("x-list").replaceChildren(...order.flatMap((k) => {
      const group = shown.filter((t) => t.category === k);
      if (!group.length) return [];
      const c = CK.get(k) || { label: k, color: "#c9c9c9" };
      const sec = el("section", "g-cat t-group");
      const h = el("h3", "q-head");
      h.style.setProperty("--sc", c.color);
      h.append(el("span", "t-gl", c.label.toUpperCase()), el("span", "rule"), el("span", "count", String(group.length)));
      sec.append(h, ...group.map(card));
      return [sec];
    }));
  }

  // ---- hash: #project=<id>&category=<key> sets filters; #<key> flashes one entry ----
  let writing = false;
  function syncHash() {
    const parts = [];
    F.project.forEach((v) => parts.push(`project=${v}`));
    F.cat.forEach((v) => parts.push(`category=${v}`));
    writing = true;
    history.replaceState(null, "", parts.length ? `#${parts.join("&")}` : location.pathname + location.search);
    writing = false;
  }
  function readHash() {
    const h = decodeURIComponent(location.hash.slice(1));
    if (!h.includes("=")) return h;
    F.cat.clear(); F.project.clear();
    h.split("&").forEach((kv) => {
      const [k, v] = kv.split("=");
      if (k === "project" && PK.has(v)) F.project.add(v);
      if (k === "category" && CK.has(v)) F.cat.add(v);
    });
    return "";
  }
  function flash(key) {
    const t = key && $(key);
    if (!t || !t.classList.contains("x-item")) return;
    t.scrollIntoView({ behavior: reduced ? "auto" : "smooth", block: "start" });
    t.classList.remove("flash"); void t.offsetWidth; t.classList.add("flash");
  }

  $("x-q").addEventListener("input", (e) => { F.q = e.target.value.trim().toLowerCase(); render(); });
  $("x-clear").addEventListener("click", () => { F.cat.clear(); F.project.clear(); F.q = ""; $("x-q").value = ""; syncHash(); render(); });
  addEventListener("hashchange", () => {
    if (writing) return;
    const key = readHash();
    if (key && IK.has(key)) {
      if (!match(IK.get(key))) { F.cat.clear(); F.project.clear(); F.q = ""; $("x-q").value = ""; }
      render(); requestAnimationFrame(() => flash(key));
    } else render();
  });

  const first = readHash();
  render();
  if (first && IK.has(first)) requestAnimationFrame(() => flash(first));

  // ---- back to top ----
  const toTop = $("to-top");
  const syncTop = () => toTop.classList.toggle("show", scrollY > innerHeight * 0.6);
  addEventListener("scroll", syncTop, { passive: true });
  toTop.addEventListener("click", () => scrollTo({ top: 0, behavior: reduced ? "auto" : "smooth" }));
  syncTop();
})();
