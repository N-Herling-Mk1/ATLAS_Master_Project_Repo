/* research-deck -- to-do page.
   Data: window.DECK_TODO {revised, flags[], items[]} plus DECK_PROJECTS / DECK_META, all from assets/js/registry.js
   (generated by tools/build_deck.py from todo/todo.json).
   Deep links: todo.html#T003 (one item), todo.html#project=<id>, todo.html#flag=<key>, todo.html#status=<status>. */
(() => {
  "use strict";
  const TD = window.DECK_TODO || { items: [], flags: [] };
  const ITEMS = TD.items || [];
  const FLAGS = TD.flags || [];
  const P = window.DECK_PROJECTS || [];
  const META = window.DECK_META || {};
  const PK = new Map(P.map((p) => [p.id, p]));
  const FK = new Map(FLAGS.map((f) => [f.key, f]));
  const IK = new Map(ITEMS.map((it) => [it.id, it]));
  const $ = (id) => document.getElementById(id);
  const reduced = matchMedia("(prefers-reduced-motion: reduce)").matches;
  const el = (tag, cls, text) => { const e = document.createElement(tag); if (cls) e.className = cls; if (text != null) e.textContent = text; return e; };
  const MONTHS = ["JAN", "FEB", "MAR", "APR", "MAY", "JUN", "JUL", "AUG", "SEP", "OCT", "NOV", "DEC"];
  const fmtDate = (d) => { const [y, m, day] = (d || "").split("-"); return [day, m && MONTHS[+m - 1], y].filter(Boolean).join(" "); };
  const STATUS = [                                       // display order
    { key: "active", label: "IN PROGRESS", color: "#39ff8f" },
    { key: "open", label: "OPEN", color: "#22c8ff" },
    { key: "blocked", label: "BLOCKED", color: "#ff4d6d" },
    { key: "done", label: "DONE", color: "#7d8590" },
  ];
  const SK = new Map(STATUS.map((s) => [s.key, s]));
  const SITE = "__site";                                 // pseudo-project for untagged items

  if (META.revised) { $("site-revised").textContent = fmtDate(META.revised); $("site-revised-wrap").hidden = false; }
  const nOpen = ITEMS.filter((it) => it.status !== "done").length;
  $("t-count").textContent = `${nOpen} OPEN · ${ITEMS.length} TOTAL`;
  $("t-revised").textContent = TD.revised ? `REVISED ${fmtDate(TD.revised)}` : "";
  if (!ITEMS.length) { $("t-list").textContent = "No items yet. Add them to todo/todo.json and run tools/build_deck.py."; return; }

  // ---- filter state: empty set = no restriction on that facet ----
  const F = { status: new Set(), project: new Set(), flag: new Set(), q: "" };

  // ---- side facets ----
  function chip(label, color, count, on, onClick, title) {
    const b = el("button", "t-chip");
    b.type = "button";
    b.style.setProperty("--cc", color);
    b.append(el("span", "t-chip-l", label));
    if (count) b.append(el("span", "t-chip-n", String(count)));          // open count; nothing when all done
    b.setAttribute("aria-pressed", on ? "true" : "false");
    if (title) b.title = title;
    b.addEventListener("click", onClick);
    return b;
  }
  const projOf = (it) => (it.projects && it.projects.length ? it.projects : [SITE]);
  const usedProjects = [...new Set(ITEMS.flatMap(projOf))]
    .sort((a, b) => (a === SITE) - (b === SITE) || (PK.get(a)?.order ?? 999) - (PK.get(b)?.order ?? 999));
  const usedFlags = FLAGS.filter((f) => ITEMS.some((it) => (it.flags || []).includes(f.key)));

  function toggle(set, key) { set.has(key) ? set.delete(key) : set.add(key); syncHash(); render(); }

  function renderFacets() {
    $("t-status").replaceChildren(...STATUS.filter((s) => ITEMS.some((it) => it.status === s.key)).map((s) =>
      chip(s.label, s.color, ITEMS.filter((it) => it.status === s.key).length, F.status.has(s.key), () => toggle(F.status, s.key))));
    $("t-projects").replaceChildren(...usedProjects.map((pid) => {
      const p = PK.get(pid);
      return chip(p ? p.name : "SITE-WIDE", p ? p.accent : "#c9c9c9", ITEMS.filter((it) => projOf(it).includes(pid) && it.status !== "done").length,
        F.project.has(pid), () => toggle(F.project, pid), "Open items for this project");
    }));
    $("t-flags").replaceChildren(...usedFlags.map((f) =>
      chip(f.label, f.color, ITEMS.filter((it) => (it.flags || []).includes(f.key) && it.status !== "done").length,
        F.flag.has(f.key), () => toggle(F.flag, f.key), "Open items with this flag")));
    $("t-clear").hidden = !(F.status.size || F.project.size || F.flag.size || F.q);
  }

  // ---- items ----
  function card(it) {
    const s = SK.get(it.status) || STATUS[1];
    const art = el("article", `t-item st-${it.status}`);
    art.id = it.id;
    art.style.setProperty("--sc", s.color);
    const head = el("div", "t-head");
    const id = el("a", "t-id", it.id);
    id.href = `#${it.id}`;
    id.title = "Link to this item";
    head.append(id, el("span", "t-st", s.label));
    const dates = it.status === "done" && it.done ? `ADDED ${fmtDate(it.added)} · DONE ${fmtDate(it.done)}` : `ADDED ${fmtDate(it.added)}`;
    head.append(el("span", "t-dates", dates));
    art.append(head, el("p", "t-text", it.text));
    if (it.detail) art.append(el("p", "t-detail", it.detail));
    const foot = el("div", "t-foot");
    const row = (k, nodes) => { if (!nodes.length) return; const r = el("p", "g-row"); r.append(el("span", "g-k", k), ...nodes); foot.append(r); };
    row("PROJECTS", projOf(it).map((pid) => {
      const p = PK.get(pid);
      if (!p) return el("span", "g-chip", "SITE-WIDE");
      const a = el("a", "g-chip g-proj", p.name);
      a.href = `index.html#${pid}`;
      a.style.setProperty("--pc", p.accent);
      return a;
    }));
    row("FLAGS", (it.flags || []).map((k) => { const f = FK.get(k); const c = el("span", "t-flag", f ? f.label : k); c.style.setProperty("--cc", f ? f.color : "#c9c9c9"); return c; }));
    row("AFTER", (it.after || []).map((k) => {
      const dep = IK.get(k);
      const a = el("a", `g-chip t-dep${dep && dep.status === "done" ? " dep-done" : ""}`, dep && dep.status === "done" ? `${k} ✓` : k);
      a.href = `#${k}`;
      a.title = dep ? dep.text : k;
      return a;
    }));
    if (foot.childNodes.length) art.append(foot);
    return art;
  }

  const hay = (it) => [it.id, it.text, it.detail || "", ...(it.projects || []).map((pid) => PK.get(pid)?.name || pid),
    ...(it.flags || []).map((k) => FK.get(k)?.label || k)].join(" ").toLowerCase().replace(/[\\$]/g, "");
  const match = (it) =>
    (!F.status.size || F.status.has(it.status)) &&
    (!F.project.size || projOf(it).some((pid) => F.project.has(pid))) &&
    (!F.flag.size || (it.flags || []).some((k) => F.flag.has(k))) &&
    (!F.q || hay(it).includes(F.q));

  function render() {
    renderFacets();
    const shown = ITEMS.filter(match);
    $("t-empty").hidden = shown.length > 0;
    $("t-list").replaceChildren(...STATUS.flatMap((s) => {
      const group = shown.filter((it) => it.status === s.key);
      if (!group.length) return [];
      const sec = el("section", `g-cat t-group grp-${s.key}`);
      const h = el("h3", "q-head");
      h.style.setProperty("--sc", s.color);
      h.append(el("span", "t-gl", s.label), el("span", "rule"), el("span", "count", String(group.length)));
      sec.append(h, ...group.map(card));
      return [sec];
    }));
    typeset($("t-list"));
  }

  function typeset(node) {
    if (!window.renderMathInElement) return;
    window.renderMathInElement(node, {
      delimiters: [{ left: "$$", right: "$$", display: true }, { left: "$", right: "$", display: false }],
      throwOnError: false,
      ignoredTags: ["script", "noscript", "style", "textarea", "pre", "code", "option", "input"],
    });
  }

  // ---- hash: #project=<id>&flag=<key>&status=<s> sets filters; #T003 flashes one item ----
  let writing = false;
  function syncHash() {
    const parts = [];
    F.project.forEach((v) => parts.push(`project=${v}`));
    F.flag.forEach((v) => parts.push(`flag=${v}`));
    F.status.forEach((v) => parts.push(`status=${v}`));
    writing = true;
    history.replaceState(null, "", parts.length ? `#${parts.join("&")}` : location.pathname + location.search);
    writing = false;
  }
  function readHash() {
    const h = decodeURIComponent(location.hash.slice(1));
    if (!h.includes("=")) return h;
    F.status.clear(); F.project.clear(); F.flag.clear();
    h.split("&").forEach((kv) => {
      const [k, v] = kv.split("=");
      if (k === "project" && (PK.has(v) || v === SITE)) F.project.add(v);
      if (k === "flag" && FK.has(v)) F.flag.add(v);
      if (k === "status" && SK.has(v)) F.status.add(v);
    });
    return "";
  }
  function flash(id) {
    const t = id && $(id);
    if (!t || !t.classList.contains("t-item")) return;
    t.scrollIntoView({ behavior: reduced ? "auto" : "smooth", block: "start" });
    t.classList.remove("flash"); void t.offsetWidth; t.classList.add("flash");
  }

  $("t-q").addEventListener("input", (e) => { F.q = e.target.value.trim().toLowerCase().replace(/[\\$]/g, ""); render(); });
  $("t-clear").addEventListener("click", () => { F.status.clear(); F.project.clear(); F.flag.clear(); F.q = ""; $("t-q").value = ""; syncHash(); render(); });
  addEventListener("hashchange", () => {
    if (writing) return;
    const id = readHash();
    if (id && IK.has(id)) {                               // a link to one item clears filters that would hide it
      if (!match(IK.get(id))) { F.status.clear(); F.project.clear(); F.flag.clear(); F.q = ""; $("t-q").value = ""; }
      render(); requestAnimationFrame(() => flash(id));
    } else render();
  });

  const first = readHash();
  render();
  if (first && IK.has(first)) requestAnimationFrame(() => flash(first));

  // ---- back to top ----
  const toTop = $("to-top");
  const syncTop = () => toTop.classList.toggle("show", scrollY > innerHeight * 0.6);
  addEventListener("scroll", syncTop, { passive: true });
  toTop.addEventListener("click", () => scrollTo({ top: 0, behavior: reduced ? "auto" : "smooth" }));
  syncTop();
})();
