/* research-deck -- gallery + stage controller.
   Data comes from window.DECK_PROJECTS (assets/js/registry.js, generated by tools/build_deck.py).
   Routing: #<project-id>. Keys: Left/Right, 1-9. Swipe on the stage. */
(() => {
  "use strict";
  const P = window.DECK_PROJECTS || [];
  if (!P.length) { document.getElementById("stage").textContent = "No projects found. Run tools/build_deck.py."; return; }

  const $ = (id) => document.getElementById(id);
  const strip = $("strip"), stage = $("stage"), root = document.documentElement;
  const pad = (n) => String(n).padStart(2, "0");
  const reduced = matchMedia("(prefers-reduced-motion: reduce)").matches;
  let cur = -1, timer = 0, first = true;

  // ---- gallery of rogues -------------------------------------------------
  const cards = P.map((p, i) => {
    const b = document.createElement("button");
    b.className = `rogue st-${p.status}`;
    b.setAttribute("role", "listitem");
    b.setAttribute("aria-label", `${p.name}: ${p.expansion}`);
    b.style.setProperty("--rc", p.accent);
    b.innerHTML =
      `<img src="${p.thumb}" alt="" width="480" height="300" loading="${i < 6 ? "eager" : "lazy"}">` +
      `<span class="r-name"><span>${p.name}</span><span class="r-dot" title="${p.status}"></span></span>`;
    b.addEventListener("click", () => go(i));
    strip.appendChild(b);
    return b;
  });

  // preload heroes after first paint so switching is instant
  addEventListener("load", () => P.forEach((p) => { const im = new Image(); im.src = p.logo; }));

  // ---- render --------------------------------------------------------------
  function render(i) {
    const p = P[i], n = P.length;
    root.style.setProperty("--a", p.accent);
    root.style.setProperty("--a2", p.accent2 || p.accent);
    document.querySelector('meta[name="theme-color"]').content = p.accent;

    $("hero-img").src = p.logo;
    $("hero-img").alt = `${p.name} logo`;
    $("counter").textContent = `${pad(i + 1)} / ${pad(n)}`;
    $("k-index").textContent = `PROJECT ${pad(i + 1)}`;
    const st = $("k-status");
    st.textContent = p.status.toUpperCase();
    st.className = `status st-${p.status}`;
    renderTitle(p);
    const tg = $("p-tagline");
    tg.hidden = !p.tagline;
    tg.textContent = p.tagline || "";

    const t = p.intro;
    $("p-intro").textContent = [t.problem, t.value, t.approach, t.goals].join(" ");

    const ol = $("p-questions");
    ol.replaceChildren(...p.questions.map((q) => { const li = document.createElement("li"); li.textContent = q; return li; }));

    renderProgram(p.components || []);
    renderLinks(p.links || []);
    renderOpen(p.open || []);
    renderTimeline(p.timeline || []);
    renderLiterature(p.literature || []);
    renderMap(p);

    const meta = $("p-meta");
    meta.replaceChildren();
    const tag = document.createElement("span");
    tag.className = "tag";
    tag.textContent = p.code === "public" ? "CODE: PUBLIC" : "CODE: INTERNAL";
    meta.appendChild(tag);
    if (p.link) {
      const a = document.createElement("a");
      a.href = p.link; a.target = "_blank"; a.rel = "noopener";
      a.textContent = p.link.replace(/^https?:\/\//, "") + " ↗";
      meta.appendChild(a);
    }

    const prev = P[(i - 1 + n) % n], next = P[(i + 1) % n];
    $("nb-prev-name").textContent = prev.name;
    $("nb-next-name").textContent = next.name;

    cards.forEach((c, k) => c.setAttribute("aria-current", k === i ? "true" : "false"));
    const c = cards[i];                        // centre the card in the strip without moving the page
    strip.scrollTo({ left: c.offsetLeft - (strip.clientWidth - c.offsetWidth) / 2, behavior: reduced || first ? "auto" : "smooth" });
    first = false;
    document.title = `${p.name} · Research Deck`;
  }

  // ---- sections ------------------------------------------------------------
  const el = (tag, cls, text) => { const e = document.createElement(tag); if (cls) e.className = cls; if (text != null) e.textContent = text; return e; };

  // ---- acronym title + expansion ---------------------------------------------
  // Find, for each letter of the acronym, the character in the expansion that spells it:
  //   1) next word-initial with that letter   (Topology Refinement Under ...)
  //   2) next exact capital inside a word     (eXperiment, tokeNs)
  //   3) any unused word-initial, out of order (Game-Theoretic -> the T in GAMBIT)
  // Names with spaces, or any letter that can't be placed, are not treated as acronyms.
  function acronymMarks(name, exp) {
    if (/\s/.test(name.trim())) return null;
    const letters = name.replace(/[^A-Za-z]/g, "").toUpperCase();
    const starts = [];
    exp.replace(/[A-Za-z][A-Za-z']*/g, (w, i) => { starts.push(i); return w; });
    const used = new Set();
    let pos = 0;
    for (const L of letters) {
      let hit = starts.find((i) => i >= pos && !used.has(i) && exp[i].toUpperCase() === L);
      if (hit === undefined) {
        const j = exp.indexOf(L, pos);
        if (j >= 0 && !used.has(j)) hit = j;
      }
      if (hit === undefined) {
        hit = starts.find((i) => !used.has(i) && exp[i].toUpperCase() === L);
        if (hit === undefined) return null;
        used.add(hit);
        continue;                                   // out-of-order match: keep scanning from pos
      }
      used.add(hit);
      pos = hit + 1;
    }
    return used;
  }

  function renderTitle(p) {
    const h = $("p-name"), x = $("p-exp");
    const marks = acronymMarks(p.name, p.expansion || "");
    h.setAttribute("aria-label", p.name);
    x.replaceChildren();
    if (!marks) {
      h.replaceChildren(document.createTextNode(p.name));
      x.textContent = p.expansion || "";
      x.classList.remove("acro");
      return;
    }
    const chars = [...p.name.replace(/[^A-Za-z]/g, "")];
    h.replaceChildren(...chars.flatMap((c, i) => {
      const s = el("span", null, c);
      s.setAttribute("aria-hidden", "true");
      if (i === chars.length - 1) return [s];
      const d = el("span", "dot", ".");
      d.setAttribute("aria-hidden", "true");
      return [s, d];
    }));
    x.classList.add("acro");
    const e = p.expansion;
    let buf = "";
    for (let i = 0; i < e.length; i++) {
      if (marks.has(i)) {
        if (buf) { x.append(document.createTextNode(buf)); buf = ""; }
        x.append(el("b", "init", e[i]));
      } else buf += e[i];
    }
    if (buf) x.append(document.createTextNode(buf));
  }

  const STATE_TAG = { done: "DONE", active: "IN PROGRESS", next: "PLANNED" };

  function renderProgram(comps) {
    $("p-program-wrap").hidden = !comps.length;
    $("p-program").replaceChildren(...comps.map((c, i) => {
      const li = el("li", `prog st-${c.state || "next"}`);
      li.id = `prog-${i}`;
      const head = el("div", "prog-head");
      head.append(el("span", "prog-n", pad(i + 1)), el("span", "prog-name", c.name));
      if (c.state) head.append(el("span", "prog-state", STATE_TAG[c.state]));
      li.append(head);
      if (c.subtitle) li.append(el("p", "prog-sub", c.subtitle));
      li.append(el("p", "prog-sum", c.summary));
      if (c.items && c.items.length) {
        const dl = el("dl", "prog-items");
        c.items.forEach((it) => dl.append(el("dt", null, it.label), el("dd", null, it.detail)));
        li.append(dl);
      }
      return li;
    }));
  }

  function renderLinks(links) {
    $("p-links-wrap").hidden = !links.length;
    $("p-links").replaceChildren(...links.map((l) => {
      const tgt = P.find((q) => q.id === l.project);
      const card = el("div", "xlink");
      if (!tgt) return card;
      card.style.setProperty("--xc", tgt.accent);
      const img = el("img");
      img.src = tgt.thumb; img.alt = ""; img.width = 160; img.height = 100;
      const body = el("div", "xl-body");
      body.append(el("p", "xl-kicker", `${tgt.name} · ${l.title}`), el("p", "xl-text", l.text));
      const btn = el("button", "xl-go", `OPEN ${tgt.name} ▶`);
      btn.type = "button";
      btn.addEventListener("click", () => {
        go(P.indexOf(tgt));
        scrollTo({ top: 0, behavior: reduced ? "auto" : "smooth" });
      });
      body.append(btn);
      card.append(img, body);
      return card;
    }));
  }
  const MONTHS = ["JAN","FEB","MAR","APR","MAY","JUN","JUL","AUG","SEP","OCT","NOV","DEC"];
  const fmtDate = (d) => {
    if (!d) return "NEXT";
    const [y, m, day] = d.split("-");
    return [day, m && MONTHS[+m - 1], y].filter(Boolean).join(" ");
  };
  const KIND = { question: "OPEN QUESTION", lesson: "NOT YET APPLIED", gap: "GAP" };

  function renderOpen(items) {
    $("p-open-wrap").hidden = !items.length;
    $("p-open").replaceChildren(...items.map((o) => {
      const li = el("li", `k-${o.kind}`);
      li.append(el("span", "kind", KIND[o.kind] || o.kind.toUpperCase()), el("span", null, o.text));
      return li;
    }));
  }

  function renderTimeline(items) {
    $("p-timeline").replaceChildren(...items.map((t) => {
      const li = el("li", `st-${t.state}`);
      li.append(el("span", "tl-date", t.state === "active" && !t.date ? "NOW" : fmtDate(t.date)), el("span", "tl-label", t.label));
      return li;
    }));
  }

  function renderLiterature(refs) {
    const box = $("p-lit");
    $("lit-count").textContent = refs.length ? `${refs.length} SOURCES` : "";
    if (!refs.length) { box.replaceChildren(el("p", "lit-empty", "Literature pass not yet recorded.")); return; }
    const groups = new Map();
    refs.forEach((r) => { if (!groups.has(r.category)) groups.set(r.category, []); groups.get(r.category).push(r); });
    const openAll = refs.length <= 12;
    box.replaceChildren(...[...groups].map(([cat, list], gi) => {
      const d = el("details", "lit-group");
      d.id = `lit-g-${gi}`;
      d.open = openAll || gi === 0;
      const s = el("summary");
      s.append(el("span", "g-name", cat.toUpperCase()), el("span", "g-n", String(list.length)));
      const ul = el("ul", "lit-list");
      list.forEach((r) => {
        const li = el("li");
        const a = el("a", null, r.title);
        a.href = r.url; a.target = "_blank"; a.rel = "noopener";
        li.append(el("span", "ref-auth", `${r.authors} (${r.year}). `), a, document.createTextNode(" "), el("span", "ref-venue", r.venue));
        if (r.why) li.append(el("span", "ref-why", r.why));
        ul.append(li);
      });
      d.append(s, ul);
      return d;
    }));
  }

  // ---- page map: in-page jumps (buttons, not anchors: the URL hash is the project route) ----
  let mapTargets = [], pinned = null;
  // sections near the page bottom can't scroll to the top, so a click pins the highlight;
  // any manual scroll input hands control back to the spy
  ["wheel", "touchmove", "keydown"].forEach((ev) => addEventListener(ev, () => { pinned = null; }, { passive: true }));

  function jump(target) {
    if (target.tagName === "DETAILS") target.open = true;
    target.scrollIntoView({ behavior: reduced ? "auto" : "smooth", block: "start" });
  }

  function renderMap(p) {
    const lit = p.literature || [];
    const cats = [...new Set(lit.map((r) => r.category))];
    const items = [
      { id: "sec-overview", label: "OVERVIEW" },
      (p.components || []).length && { id: "sec-program", label: "PROGRAM", n: p.components.length,
        sub: p.components.map((c, j) => ({ id: `prog-${j}`, label: c.name.toUpperCase() })) },
      (p.links || []).length && { id: "sec-links", label: "LINKED PROJECTS", n: p.links.length },
      { id: "sec-questions", label: "QUESTIONS", n: p.questions.length },
      (p.open || []).length && { id: "p-open-wrap", label: "OPEN ITEMS", n: p.open.length },
      { id: "sec-progress", label: "PROGRESS", n: (p.timeline || []).length },
      { id: "sec-literature", label: "LITERATURE", n: lit.length,
        sub: cats.map((c, gi) => ({ id: `lit-g-${gi}`, label: c.toUpperCase(), n: lit.filter((r) => r.category === c).length })) },
    ].filter(Boolean);

    mapTargets = [];
    pinned = null;
    const mk = (it, num) => {
      const b = el("button", "pm-link");
      b.type = "button";
      b.append(el("span", "pm-n", num), el("span", "pm-l", it.label), el("span", "pm-c", it.n != null ? String(it.n) : ""));
      b.addEventListener("click", () => {
        const t = $(it.id);
        if (!t) return;
        pinned = it.id;                              // trust the click until the user scrolls by hand
        mapTargets.forEach((m) => m.btn.classList.toggle("on", m.id === it.id));
        jump(t);
      });
      mapTargets.push({ id: it.id, btn: b });
      return b;
    };
    $("pagemap").replaceChildren(...items.map((it, k) => {
      const li = el("li");
      li.append(mk(it, pad(k + 1)));
      if (it.sub && it.sub.length) {
        const ul = el("ol", "pm-sub");
        it.sub.forEach((s, j) => { const sl = el("li"); sl.append(mk(s, `${pad(k + 1)}.${j + 1}`)); ul.append(sl); });
        li.append(ul);
      }
      return li;
    }));
    spy();
  }

  // highlight the section(s) whose top most recently passed 35% of the viewport;
  // side-by-side sections (progress | literature) share a top and light together
  function spy() {
    if (pinned) return;
    const line = innerHeight * 0.35;
    let best = -Infinity, on = [];
    for (const t of mapTargets) {
      const node = $(t.id);
      if (!node || node.offsetParent === null) continue;
      const top = Math.round(node.getBoundingClientRect().top);
      if (top > line) continue;
      if (top > best + 2) { best = top; on = [t]; }
      else if (Math.abs(top - best) <= 2) on.push(t);
    }
    if (!on.length && mapTargets.length) on = [mapTargets[0]];
    mapTargets.forEach((t) => t.btn.classList.toggle("on", on.includes(t)));
  }
  let spyQueued = false;
  addEventListener("scroll", () => {
    if (spyQueued) return;
    spyQueued = true;
    requestAnimationFrame(() => { spyQueued = false; spy(); });
  }, { passive: true });

  function go(i, push = true) {
    const n = P.length;
    i = ((i % n) + n) % n;
    if (i === cur) return;
    cur = i;
    if (push && location.hash.slice(1) !== P[i].id) history.replaceState(null, "", `#${P[i].id}`);
    if (reduced) { render(i); return; }
    clearTimeout(timer);                       // latest input always wins
    stage.classList.add("out");
    timer = setTimeout(() => { render(cur); stage.classList.remove("out"); }, 170);
  }

  const idxFromHash = () => Math.max(0, P.findIndex((p) => p.id === location.hash.slice(1)));

  // ---- controls ------------------------------------------------------------
  $("prev").onclick = $("nb-prev").onclick = () => go(cur - 1);
  $("next").onclick = $("nb-next").onclick = () => go(cur + 1);

  addEventListener("keydown", (e) => {
    if (e.altKey || e.ctrlKey || e.metaKey) return;
    if (e.key === "ArrowRight") { go(cur + 1); e.preventDefault(); }
    else if (e.key === "ArrowLeft") { go(cur - 1); e.preventDefault(); }
    else if (/^[1-9]$/.test(e.key) && +e.key <= P.length) go(+e.key - 1);
  });
  addEventListener("hashchange", () => go(idxFromHash(), false));

  let x0 = null, y0 = null;
  stage.addEventListener("touchstart", (e) => { x0 = e.touches[0].clientX; y0 = e.touches[0].clientY; }, { passive: true });
  stage.addEventListener("touchend", (e) => {
    if (x0 === null) return;
    const dx = e.changedTouches[0].clientX - x0, dy = e.changedTouches[0].clientY - y0;
    if (Math.abs(dx) > 60 && Math.abs(dx) > 1.5 * Math.abs(dy)) go(cur + (dx < 0 ? 1 : -1));
    x0 = y0 = null;
  }, { passive: true });

  // ---- boot ----------------------------------------------------------------
  cur = idxFromHash();
  render(cur);
})();
