  // ---- acronym title + expansion ---------------------------------------------
  // Find, for each letter of the acronym, the character in the expansion that spells it:
  //   0) the capital right after the previous hit (a capital run: UNsupervised -> U, N)
  //   1) next word-initial with that letter   (Topology Refinement Under ...)
  //   2) next exact capital inside a word     (eXperiment, tokeNs)
  //   3) any unused word-initial, out of order (Game-Theoretic -> the T in GAMBIT)
  // Names with spaces, or any letter that can't be placed, are not treated as acronyms.
  function acronymMarks(name, exp) {
    if (/\s/.test(name.trim())) return null;
    const letters = name.replace(/[^A-Za-z]/g, "").toUpperCase();
    const starts = [];
    exp.replace(/[A-Za-z][A-Za-z']*/g, (w, i) => { starts.push(i); return w; });
    const used = new Set();
    let pos = 0;
    for (const L of letters) {
      let hit = pos > 0 && used.has(pos - 1) && exp[pos] === L ? pos : undefined;
      if (hit === undefined) hit = starts.find((i) => i >= pos && !used.has(i) && exp[i].toUpperCase() === L);
      if (hit === undefined) {
        const j = exp.indexOf(L, pos);
        if (j >= 0 && !used.has(j)) hit = j;
      }
      if (hit === undefined) {
        hit = starts.find((i) => !used.has(i) && exp[i].toUpperCase() === L);
        if (hit === undefined) return null;
        used.add(hit);
        continue;                                   // out-of-order match: keep scanning from pos
      }
      used.add(hit);
      pos = hit + 1;
    }
    return used;
  }

  function renderTitle(p, hId = "p-name", xId = "p-exp") {
    const h = $(hId), x = $(xId);
    const marks = acronymMarks(p.name, p.expansion || "");
    h.setAttribute("aria-label", p.name);
    x.replaceChildren();
    if (!marks) {
      h.replaceChildren(document.createTextNode(p.name));
      x.textContent = p.expansion || "";
      x.classList.remove("acro");
      return;
    }
    const chars = [...p.name.replace(/[^A-Za-z]/g, "")];
    h.replaceChildren(...chars.flatMap((c, i) => {
      const s = el("span", null, c);
      s.setAttribute("aria-hidden", "true");
      if (i === chars.length - 1) return [s];
      const d = el("span", "dot", ".");
      d.setAttribute("aria-hidden", "true");
      return [s, d];
    }));
    x.classList.add("acro");
    const e = p.expansion;
    let buf = "";
    for (let i = 0; i < e.length; i++) {
      if (marks.has(i)) {
        if (buf) { x.append(document.createTextNode(buf)); buf = ""; }
        x.append(el("b", "init", e[i]));
      } else buf += e[i];
    }
    if (buf) x.append(document.createTextNode(buf));
  }

  // ---- inline citations: "[@key]" -> numbered superscript linked to the literature list ----
  const CITE_RE = /((?:\[@[\w-]+\])+)/g;
  let citeNum = new Map();

  function buildCites(p) {
    citeNum = new Map();
    const texts = [p.intro.problem, p.intro.value, p.intro.approach, p.intro.goals];
    (p.components || []).forEach((c) => { texts.push(c.summary); (c.items || []).forEach((it) => texts.push(it.detail)); });
    (p.results || []).forEach((r) => texts.push(r.text));
    const keys = new Set((p.literature || []).map((r) => r.key).filter(Boolean));
    texts.join(" ").replace(/\[@([\w-]+)\]/g, (_, k) => { if (keys.has(k) && !citeNum.has(k)) citeNum.set(k, citeNum.size + 1); return _; });
  }

  function citeNodes(text) {
    const out = [];
    text.split(CITE_RE).forEach((part, i) => {
      if (i % 2 === 0) { if (part) out.push(...termNodes(part)); return; }
      const ks = [...part.matchAll(/\[@([\w-]+)\]/g)].map((m) => m[1]).filter((k) => citeNum.has(k));
      if (!ks.length) return;
      const sup = el("sup", "cite");
      sup.append(document.createTextNode("["));
      ks.forEach((k, j) => {
        if (j) sup.append(document.createTextNode(","));
        const b = el("button", "cite-n", String(citeNum.get(k)));
        b.type = "button";
        const ref = (P[cur].literature || []).find((r) => r.key === k);
        if (ref) b.title = `${ref.authors} (${ref.year}). ${ref.title}`;
        b.addEventListener("click", () => {
          const li = $(`ref-${k}`);
          if (!li) return;
          const grp = li.closest("details");
          if (grp) grp.open = true;
          pinned = "sec-literature";
          mapTargets.forEach((m) => m.btn.classList.toggle("on", m.id === "sec-literature"));
          li.scrollIntoView({ behavior: reduced ? "auto" : "smooth", block: "center" });
          li.classList.remove("flash"); void li.offsetWidth; li.classList.add("flash");
        });
        sup.append(b);
      });
      sup.append(document.createTextNode("]"));
      out.push(sup);
    });
    return out;
  }

  // ---- glossary links: "[[key]]" or "[[key|shown text]]" -> a button that opens a definition card ----
  const TERM_RE = /\[\[([a-z0-9-]+)(?:\|([^\]]+))?\]\]/g;
  // inline label for a [[key]] link: the term's 'inline' field, else its name with a sentence-case first letter lowered
  const inlineName = (t) => t.inline || (/^[A-Z][a-z]/.test(t.term) && !/[A-Z]/.test(t.term.slice(1)) ? t.term[0].toLowerCase() + t.term.slice(1) : t.term);

  function termNodes(text) {
    const out = [];
    let last = 0;
    for (const m of text.matchAll(TERM_RE)) {
      if (m.index > last) out.push(document.createTextNode(text.slice(last, m.index)));
      const t = GK.get(m[1]);
      const shown = m[2] || (t ? inlineName(t) : m[1]);
      if (!t) out.push(document.createTextNode(shown));
      else {
        const b = el("button", "term", shown);
        b.type = "button";
        b.dataset.term = t.key;
        b.setAttribute("aria-haspopup", "dialog");
        b.setAttribute("aria-label", `Definition: ${shown.replace(/\$/g, "")}`);
        b.addEventListener("click", (e) => { e.stopPropagation(); openPop(t, b); });
        out.push(b);
      }
      last = m.index + m[0].length;
    }
    if (last < text.length) out.push(document.createTextNode(text.slice(last)));
    return out;
  }

  const pop = el("div", "term-pop");
  pop.setAttribute("role", "dialog");
  pop.hidden = true;
  document.body.appendChild(pop);
  let popFor = null;

  function openPop(t, anchor) {
    if (popFor === anchor && !pop.hidden) { closePop(); return; }
    popFor = anchor;
    pop.style.setProperty("--a", getComputedStyle(root).getPropertyValue("--a"));
    const head = el("p", "tp-head");
    head.append(el("span", "tp-cat", t.category.toUpperCase()), el("button", "tp-x", "✕"));
    head.lastChild.type = "button";
    head.lastChild.setAttribute("aria-label", "Close");
    head.lastChild.addEventListener("click", closePop);
    const name = el("p", "tp-term", t.term);
    const body = el("p", "tp-short");
    // links inside a definition go to the glossary page rather than stacking cards
    body.append(...t.short.split(TERM_RE).reduce((acc, part, i, arr) => {
      if (i % 3 === 0) { if (part) acc.push(document.createTextNode(part)); }
      else if (i % 3 === 1) {
        const tt = GK.get(part), a = el("a", "tp-link", arr[i + 1] || (tt ? inlineName(tt) : part));
        a.href = `glossary.html#${part}`;
        acc.push(a);
      }
      return acc;
    }, []));
    const more = el("a", "tp-more", "FULL ENTRY IN THE GLOSSARY ▶");
    more.href = `glossary.html#${t.key}`;
    pop.replaceChildren(head, name);
    if (t.aka && t.aka.length) pop.append(el("p", "tp-aka", `also: ${t.aka.join(" · ")}`));
    pop.append(body, more);
    pop.hidden = false;
    typeset(pop);
    // place under the anchor, kept inside the viewport
    const r = anchor.getBoundingClientRect(), w = Math.min(420, innerWidth - 24);
    pop.style.width = `${w}px`;
    let left = r.left + scrollX;
    left = Math.max(12 + scrollX, Math.min(left, scrollX + innerWidth - w - 12));
    let top = r.bottom + scrollY + 8;
    pop.style.left = `${left}px`;
    pop.style.top = `${top}px`;
    const ph = pop.offsetHeight;
    if (r.bottom + 8 + ph > innerHeight && r.top - 8 - ph > 0) pop.style.top = `${r.top + scrollY - 8 - ph}px`;
    pop.querySelector(".tp-x").focus({ preventScroll: true });
  }
  function closePop() {
    if (pop.hidden) return;
    pop.hidden = true;
    if (popFor && document.activeElement && pop.contains(document.activeElement)) popFor.focus({ preventScroll: true });
    popFor = null;
  }
  document.addEventListener("click", (e) => { if (!pop.hidden && !pop.contains(e.target)) closePop(); });
  addEventListener("keydown", (e) => { if (e.key === "Escape") closePop(); });
  addEventListener("resize", closePop);

  // ---- math: KaTeX auto-render over $...$ and $$...$$ (vendored in assets/vendor/katex) ----
  function typeset(node) {
    if (!window.renderMathInElement) return;
    window.renderMathInElement(node, {
      delimiters: [{ left: "$$", right: "$$", display: true }, { left: "$", right: "$", display: false }],
      throwOnError: false,
      ignoredTags: ["script", "noscript", "style", "textarea", "pre", "code", "option"],
    });
  }

  const STATE_TAG = { done: "DONE", active: "IN PROGRESS", next: "PLANNED" };

  function renderProgram(comps) {
    $("p-program-wrap").hidden = !comps.length;
    $("p-program").replaceChildren(...comps.map((c, i) => {
      const li = el("li", `prog st-${c.state || "next"}`);
      li.id = `prog-${i}`;
      li.dataset.slug = c.slug || "";
      const head = el("div", "prog-head");
      head.append(el("span", "prog-n", pad(i + 1)), el("span", "prog-name", c.codename || c.name));
      if (c.state) head.append(el("span", "prog-state", STATE_TAG[c.state]));
      li.append(head);
      if (c.codename) li.append(el("p", "prog-desc", c.name));
      if (c.subtitle) li.append(el("p", "prog-sub", c.subtitle));
      const sum = el("p", "prog-sum");
      sum.append(...citeNodes(c.summary));
      li.append(sum);
      if (c.items && c.items.length) {
        const dl = el("dl", "prog-items");
        c.items.forEach((it) => { const dd = el("dd"); dd.append(...citeNodes(it.detail)); dl.append(el("dt", null, it.label), dd); });
        li.append(dl);
      }
      if (c.page) {
        const a = el("a", "prog-open", `OPEN ${(c.codename || c.name).toUpperCase()} SUB-PAGE`);
        a.href = `#${P[cur].id}/${c.slug}`;
        a.append(el("span", "po-arrow", " ▶"));
        li.append(a);
      }
      return li;
    }));
  }

  // ---- sub-project strip: one line per program under the intro, each a jump link ----
  // The URL becomes #<project>/<slug>, so a sub-project can be linked to directly.
  const synopsisOf = (c) => c.synopsis || (c.subtitle || "").replace(/^Program\s+\d+\s*·\s*/i, "");

  // 'sub_label' (optional, per project) renames SUB-PROJECT for that project, e.g. CHAPTER
  const subLabel = (p) => (p && p.sub_label) || "SUB-PROJECT";

  function renderSubs(p) {
    const comps = p.components || [];
    $("subs-label").textContent = `${subLabel(p)}S`;
    const wrap = $("p-subs-wrap");
    wrap.hidden = comps.length < 2;
    $("subs-count").textContent = comps.length ? String(comps.length) : "";
    $("p-subs").replaceChildren(...comps.map((c, i) => {
      const b = el("button", `sub st-${c.state || "next"}`);
      b.type = "button";
      b.title = c.page ? `Open the ${c.codename || c.name} sub-page` : `Jump to ${c.codename || c.name}`;
      if (c.page) b.classList.add("has-page");
      const top = el("span", "sub-top");
      top.append(el("span", "sub-n", pad(i + 1)), el("i", "sub-led"), el("span", "sub-state", STATE_TAG[c.state] || ""));
      b.append(top, el("span", "sub-name", c.codename || c.name));
      const syn = synopsisOf(c);
      if (syn) b.append(el("span", "sub-syn", syn));
      if (c.page) b.append(el("span", "sub-open", "OPEN ▶"));
      b.addEventListener("click", () => {
        if (c.page) { location.hash = `#${p.id}/${c.slug}`; return; }   // new history entry: Back returns here
        if (c.slug) history.replaceState(null, "", `#${p.id}/${c.slug}`);
        showSub(c.slug, i);
      });
      return b;
    }));
  }

  function showSub(slug, k, instant = false) {
    const comps = (P[cur] && P[cur].components) || [];
    if (k == null) k = comps.findIndex((c) => c.slug === slug);
    const t = k >= 0 ? $(`prog-${k}`) : null;
    if (!t) return;
    pinned = t.id;
    mapTargets.forEach((m) => m.btn.classList.toggle("on", m.id === t.id));
    jump(t, instant);
    t.classList.remove("flash"); void t.offsetWidth; t.classList.add("flash");
  }

